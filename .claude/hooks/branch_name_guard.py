"""
PreToolUse hook (Bash and GitHub MCP write tools): branches that reach GitHub
are named `<type>/<topic>`.

Claude Code names some branches itself: cloud sessions (claude.ai/code)
develop on `claude/<slug>` and `claude --worktree` creates `worktree-<name>`.
A pull request opened from one keeps that name. This blocks the moment such a
branch would reach GitHub, whenever it was created (creating or renaming it
locally is harmless):

- `git push` to one: the destination of each refspec (`claude/x`,
  `HEAD:claude/x`, `HEAD:refs/heads/claude/x`) or, with no refspec, the
  current branch. Deleting one (`--delete`, `:claude/x`) is allowed.
- `gh pr create` from one (`--head`, or the current branch).
- GitHub MCP tools that create a branch, commit to one or open a pull request
  from one (`branch`, `head`).

Other names are not checked: the rule `<type>/<topic>` is in CLAUDE.md, and a
list of allowed types would block legitimate names for little gain.

Exit code 2 blocks the call and sends the reason back to Claude. Standard
library only (runs on any Python 3).
"""

import json
import os
import re
import shlex
import subprocess
import sys

SEGMENT_SEPARATOR = re.compile(r"\n|&&|\|\||;|\|")
ENV_ASSIGNMENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*=")
# A redirection (`2>&1`, `>log`, `> log`), which is not an argument; group 1 is
# empty when the target is the next word.
REDIRECTION = re.compile(r"^(?:\d+|&)?(?:>>?|<<?|>&|<&)(.*)$")
# The start of a heredoc (`<<EOF`, `<<'EOF'`, `<<-EOF`), not a here-string (`<<<`).
HEREDOC_START = re.compile(r"(?<!<)<<(?!<)-?\s*['\"]?([A-Za-z_][A-Za-z0-9_]*)['\"]?")
# git options that take a separate value before the subcommand.
GIT_OPTIONS_WITH_VALUE = {"-C", "-c", "--git-dir", "--work-tree", "--namespace"}
# `git push` options that take a separate value.
PUSH_OPTIONS_WITH_VALUE = {"-o", "--push-option", "--repo", "--receive-pack", "--exec"}
SESSION_BRANCH = re.compile(r"^(claude/|worktree-)")
RELEASE_REF = re.compile(
    r"refs/(?:heads|remotes/origin)/(\d+)\.(\d+)\.x$", re.MULTILINE
)
TIMEOUT = 15
# GitHub MCP tools that create a branch, commit to one or open a pull request.
MCP_BRANCH_TOOL = re.compile(
    r"^mcp__.*github.*__(create_branch|push_files|create_or_update_file"
    r"|delete_file|create_pull_request)$"
)
BLOCK_MESSAGE = (
    "Blocked: '{branch}' is a branch name generated by Claude Code; "
    "branches that reach GitHub are named `<type>/<topic>` (feature, fix, docs, "
    "chore, perf; see the Git workflow in CLAUDE.md). Rename it with "
    "`git branch -m <type>/<topic>`, check that `git log --oneline "
    "origin/{release}..HEAD` lists only the commits of this work (if the "
    "branch started from `main`, move them with `git rebase --onto "
    "origin/{release} origin/main`), and push that branch instead.\n"
)


def without_heredocs(command):
    """
    Remove the body of every heredoc from `command`: its lines are data (a
    commit message, a file written with `cat`), not commands, so a line such
    as `git push` in a handoff note must not be checked as if it ran.
    """
    kept = []
    delimiter = None
    for line in command.split("\n"):
        if delimiter is not None:
            if line.strip() == delimiter:
                delimiter = None
            continue
        kept.append(line)
        match = HEREDOC_START.search(line)
        if match:
            delimiter = match.group(1)
    return "\n".join(kept)


def segments(command):
    """
    Split `command` into simple commands and return the words of each, with
    leading env assignments and redirections removed. Heredoc bodies are left
    out, and a segment that is not valid shell is skipped.
    """
    result = []
    for segment in SEGMENT_SEPARATOR.split(without_heredocs(command)):
        try:
            words = shlex.split(segment.strip().lstrip("({ "))
        except ValueError:
            continue
        while words and ENV_ASSIGNMENT.match(words[0]):
            words.pop(0)
        arguments = []
        target = False
        for word in words:
            if target:
                target = False
            elif match := REDIRECTION.match(word):
                target = match.group(1) == ""
            else:
                arguments.append(word)
        if arguments:
            result.append(arguments)
    return result


def current_branch(cwd):
    result = subprocess.run(
        ["git", "rev-parse", "--abbrev-ref", "HEAD"],
        cwd=cwd, capture_output=True, text=True,
    )
    return result.stdout.strip() if result.returncode == 0 else ""


def release_branch(cwd):
    """
    The release branch in development: the `X.Y.x` branch of `origin` with
    the highest version (from GitHub, or else from the local refs), or None.
    Not `__version__`, which on `main` (where cloud sessions may start) is
    still the previous release.
    """
    refs = []
    for args in (
        ["ls-remote", "--heads", "origin", "refs/heads/*.x"],
        ["for-each-ref", "--format=%(refname)", "refs/remotes/origin/"],
    ):
        try:
            result = subprocess.run(
                ["git", *args], cwd=cwd, capture_output=True, text=True,
                timeout=TIMEOUT, env={**os.environ, "GIT_TERMINAL_PROMPT": "0"},
            )
        except (OSError, subprocess.TimeoutExpired):
            continue
        refs = [m.groups() for m in RELEASE_REF.finditer(result.stdout)]
        if refs:
            break
    if not refs:
        return None
    major, minor = max((int(a), int(b)) for a, b in refs)
    return f"{major}.{minor}.x"


def pushed_branches(args, cwd):
    """Destination branches of `git push <args>` (the current one by default)."""
    positional = []
    i = 0
    while i < len(args):
        arg = args[i]
        if arg in ("--delete", "-d"):
            return []
        if arg in PUSH_OPTIONS_WITH_VALUE:
            i += 2
            continue
        if not arg.startswith("-"):
            positional.append(arg)
        i += 1
    refspecs = positional[1:]
    if not refspecs:
        return [current_branch(cwd)]
    branches = []
    for refspec in refspecs:
        src, _, dst = refspec.lstrip("+").partition(":")
        if _ and not src:
            continue  # `:branch` deletes it.
        dst = dst or src
        if dst in ("HEAD", "@"):
            dst = current_branch(cwd)
        branches.append(dst.removeprefix("refs/heads/"))
    return branches


def pr_head(args, cwd):
    """Head branch of `gh pr create <args>` (the current one by default)."""
    for i, arg in enumerate(args):
        if arg in ("--head", "-H") and i + 1 < len(args):
            head = args[i + 1]
        elif arg.startswith("--head="):
            head = arg.split("=", 1)[1]
        else:
            continue
        return head.split(":", 1)[-1]
    return current_branch(cwd)


def bash_branches(command, cwd):
    """Branches that a Bash command pushes or opens a pull request from."""
    branches = []
    for words in segments(command):
        name = os.path.basename(words[0])
        if name == "git":
            repo = cwd
            i = 1
            while i < len(words) and words[i].startswith("-"):
                if words[i] == "-C" and i + 1 < len(words):
                    repo = os.path.join(repo, words[i + 1])
                i += 2 if words[i] in GIT_OPTIONS_WITH_VALUE else 1
            if words[i:i + 1] == ["push"]:
                branches += pushed_branches(words[i + 1:], repo)
        elif name == "gh" and words[1:3] == ["pr", "create"]:
            branches.append(pr_head(words[3:], cwd))
    return branches


def main():
    try:
        payload = json.load(sys.stdin)
    except ValueError:
        return 0

    tool_name = payload.get("tool_name", "")
    tool_input = payload.get("tool_input") or {}
    cwd = payload.get("cwd") or os.environ.get("CLAUDE_PROJECT_DIR") or "."

    if tool_name == "Bash":
        branches = bash_branches(tool_input.get("command", ""), cwd)
    elif MCP_BRANCH_TOOL.match(tool_name):
        branches = [
            str(tool_input[key]).split(":", 1)[-1]
            for key in ("branch", "head") if tool_input.get(key)
        ]
    else:
        branches = []

    for branch in branches:
        if SESSION_BRANCH.match(branch):
            project_dir = os.environ.get("CLAUDE_PROJECT_DIR") or cwd
            sys.stderr.write(BLOCK_MESSAGE.format(
                branch=branch, release=release_branch(project_dir) or "X.Y.x"
            ))
            return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
